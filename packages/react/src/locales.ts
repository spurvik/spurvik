export type EuDisclosureLocale = keyof typeof EU_DISCLOSURE_LOCALES;

const extraLocales = new Map<string, DisclosureCopy>();

/** Register a locale that is not in the built-in EU set. */
export function registerDisclosureLocale(code: string, copy: DisclosureCopy): void {
  extraLocales.set(code.toLowerCase(), copy);
}

export function disclosureCopy(code?: string): DisclosureCopy {
  const key = (code ?? "en").toLowerCase();
  return extraLocales.get(key) ?? EU_DISCLOSURE_LOCALES[key as EuDisclosureLocale] ?? EU_DISCLOSURE_LOCALES.en;
}

export function isEuDisclosureLocale(code: string): code is EuDisclosureLocale {
  return Object.prototype.hasOwnProperty.call(EU_DISCLOSURE_LOCALES, code.toLowerCase());
}
